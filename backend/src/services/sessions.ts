const DAY = 24 * 60 * 60 * 1000;
// A browser session ends after this long without a request. Its maximum age is the token's (JWT_EXPIRES_IN).
export const WEB_SESSION_IDLE_MS = 12 * 60 * 60 * 1000;
// A browser session's lastUsedAt and idle expiry are written at most this often.
const WEB_TOUCH_INTERVAL_MS = 60 * 1000;
// A rotated-out token is accepted once more within this window: the client may never have received the new pair.
const ROTATION_GRACE_MS = 30_000;
// How many retired tokens to remember for reuse detection.
const RETIRED_TOKENS_KEPT = 20;

/** Sent with a sign-in by clients that want a device session (the mobile app). */
export const deviceSchema = z
  .object({
    name: z.string().trim().min(1).max(80),
    platform: z.enum(DEVICE_PLATFORMS),
    model: z.string().trim().max(80).optional(),
    osVersion: z.string().trim().max(40).optional(),
    appVersion: z.string().trim().max(40).optional(),
    // Generated by the app on install. Without it a phone can't turn on biometric sign-in.
    installationId: z.string().regex(/^[A-Za-z0-9-]{16,64}$/, "Invalid installation id").optional(),
  })
  .optional();

export type DeviceInfo = z.infer<typeof deviceSchema>;

/** Ends a user's live biometric sign-in keys that match `filter` (an installation, or every other one). */
export async function revokeBiometricKeys(
  userId: Types.ObjectId | string,
  filter: { installationId?: string | { $ne: string } },
  reason: BiometricRevokeReason,
) {
  if (filter.installationId === undefined) return 0;
  const result = await BiometricKeyModel.updateMany(
    { user: userId, revokedAt: null, ...filter },
    { revokedAt: new Date(), revokedReason: reason },
  );
  return result.modifiedCount;
}

export const refreshTokenSchema = z.string().min(32).max(200);

const hash = (token: string) => new Bun.CryptoHasher("sha256").update(token).digest("hex");

function newRefreshToken() {
  const bytes = crypto.getRandomValues(new Uint8Array(32));
  return `lprt_${Buffer.from(bytes).toString("base64url")}`;
}

type ClientInfo = { ip?: string; userAgent?: string };

function clientInfo(req: Request): ClientInfo {
  return { ip: req.ip, userAgent: req.get("user-agent")?.slice(0, 300) };
}

const BROWSERS: [RegExp, string][] = [
  [/Edg\//, "Edge"],
  [/OPR\//, "Opera"],
  [/Firefox\/|FxiOS/, "Firefox"],
  [/Chrome\/|CriOS/, "Chrome"],
  [/Safari\//, "Safari"],
];
// iPhones also say "Mac OS X", and Android also says "Linux", so they're checked first.
const SYSTEMS: [RegExp, string][] = [
  [/iPhone|iPad/, "iOS"],
  [/Android/, "Android"],
  [/Windows/, "Windows"],
  [/Mac OS X/, "macOS"],
  [/Linux/, "Linux"],
];

/** "Chrome on Windows", for the sessions list. The web forwards the browser's user agent when signing in. */
function browserName(ua = "") {
  const browser = BROWSERS.find(([pattern]) => pattern.test(ua))?.[1] ?? "Web browser";
  const os = SYSTEMS.find(([pattern]) => pattern.test(ua))?.[1];
  return os ? `${browser} on ${os}` : browser;
}

/**
 * Opens a browser session (the web dashboard) and returns its access token, which lasts the session's maximum age.
 * Each request through it counts as activity (see touchSession), and it ends like any other session.
 */
export async function startWebSession(
  userId: string,
  client: ClientInfo = {},
): Promise<{ accessToken: string; sessionId: string }> {
  const now = Date.now();
  const _id = new Types.ObjectId();
  const accessToken = await signAccessToken(userId, _id.toString(), env.jwtExpiresIn);
  const absoluteExpiresAt = new Date(decodeJwt(accessToken).exp! * 1000);
  await SessionModel.create({
    _id,
    user: userId,
    kind: "web",
    refreshTokenHash: hash(newRefreshToken()),
    device: { name: browserName(client.userAgent), platform: "web" },
    ...client,
    expiresAt: new Date(Math.min(now + WEB_SESSION_IDLE_MS, absoluteExpiresAt.getTime())),
    absoluteExpiresAt,
  });
  return { accessToken, sessionId: _id.toString() };
}

async function tokensFor(session: SessionDocument, refreshToken: string) {
  return {
    accessToken: await signAccessToken(session.user.toString(), session.id),
    refreshToken,
    sessionId: session.id,
  };
}

/**
 * The body every sign-in returns. Without `device` a browser session is opened and only its access token is
 * returned; with it, a device session is created and the response also carries `refreshToken` and `sessionId`.
 */
export async function signInResponse(req: Request, user: UserDocument, device: DeviceInfo) {
  // For staff looking at who is active on a business. A failure here mustn't block the sign-in.
  await UserModel.updateOne({ _id: user._id }, { lastSignInAt: new Date(), lastSignInIp: req.ip }).catch((err) =>
    console.error("Couldn't record the sign-in time:", err),
  );
  if (!device) return { accessToken: (await startWebSession(user.id, clientInfo(req))).accessToken, user };

  const now = Date.now();
  const refreshToken = newRefreshToken();
  const absoluteExpiresAt = new Date(now + env.sessionMaxAgeDays * DAY);
  const { installationId, ...deviceFields } = device;
  const session = await SessionModel.create({
    user: user._id,
    refreshTokenHash: hash(refreshToken),
    installationId,
    device: deviceFields,
    ...clientInfo(req),
    expiresAt: new Date(Math.min(now + env.sessionIdleDays * DAY, absoluteExpiresAt.getTime())),
    absoluteExpiresAt,
  });
  await alertIfNewDevice(user, session);
  return { ...(await tokensFor(session, refreshToken)), user };
}

/**
 * Tells the user about a sign-in from a phone they haven't used before. Not for their very first
 * device (just after sign-up), and not when the same installation signs in again.
 */
async function alertIfNewDevice(user: UserDocument, session: SessionDocument) {
  const others = await SessionModel.find({ user: user._id, _id: { $ne: session._id }, kind: { $ne: "web" } })
    .select("installationId")
    .lean();
  if (!others.length) return;
  if (session.installationId && others.some((o) => o.installationId === session.installationId)) return;
  await newDeviceSignIn(user._id, { name: session.device!.name, platform: session.device!.platform });
}

const invalidRefresh = () => new HttpError(401, "Your session has ended. Sign in again.", "INVALID_REFRESH_TOKEN");

const isLive = (s: SessionDocument) => !s.revokedAt && s.expiresAt.getTime() > Date.now();

/** Exchanges a refresh token for a new pair. The old token stops working (rotation). */
export async function rotateSession(req: Request, refreshToken: string) {
  const presented = hash(refreshToken);
  let session = await SessionModel.findOne({ refreshTokenHash: presented });

  if (!session) {
    const previous = await SessionModel.findOne({ previousTokenHash: presented });
    const inGrace = previous?.rotatedAt && Date.now() - previous.rotatedAt.getTime() < ROTATION_GRACE_MS;
    if (previous && inGrace) {
      session = previous;
    } else {
      // A token that was already rotated away is being replayed: someone else may hold a copy.
      const stolen = previous ?? (await SessionModel.findOne({ retiredTokenHashes: presented }));
      if (stolen && !stolen.revokedAt) {
        stolen.set({ revokedAt: new Date(), revokedReason: "reuse_detected" });
        await stolen.save();
        // Whoever holds the copy may have the rest of the phone's keychain too.
        await revokeBiometricKeys(stolen.user, { installationId: stolen.installationId ?? undefined }, "reuse_detected");
      }
      throw invalidRefresh();
    }
  }
  if (!isLive(session)) throw invalidRefresh();

  const now = Date.now();
  const next = newRefreshToken();
  const normal = session.refreshTokenHash === presented;
  // Normal rotation: the presented token becomes the one-time grace token. Grace rotation: the pair the
  // client never received is retired along with the grace token, so neither works again.
  const retired = normal ? [session.previousTokenHash] : [session.refreshTokenHash, presented];
  session.set({
    previousTokenHash: normal ? presented : undefined,
    retiredTokenHashes: [...retired.filter(Boolean), ...session.retiredTokenHashes].slice(0, RETIRED_TOKENS_KEPT),
    refreshTokenHash: hash(next),
    rotatedAt: new Date(now),
    lastUsedAt: new Date(now),
    expiresAt: new Date(Math.min(now + env.sessionIdleDays * DAY, session.absoluteExpiresAt.getTime())),
    ...clientInfo(req),
  });
  await session.save();
  return tokensFor(session, next);
}

/** Whether an access token's session is still usable, without counting as activity (for long-lived streams). */
export async function isSessionActive(sessionId: string, userId: string) {
  const session = await SessionModel.findById(sessionId).select("user revokedAt expiresAt").lean();
  return !!session && session.user.toString() === userId && !session.revokedAt && session.expiresAt.getTime() > Date.now();
}

/** Whether an access token's session is still usable. A browser session's idle expiry moves back with each request. */
export async function touchSession(sessionId: string, userId: string) {
  const session = await SessionModel.findById(sessionId).select("user kind revokedAt expiresAt absoluteExpiresAt lastUsedAt").lean();
  const now = Date.now();
  if (!session || session.user.toString() !== userId || session.revokedAt || session.expiresAt.getTime() <= now) return false;
  if (session.kind === "web" && now - (session.lastUsedAt?.getTime() ?? 0) >= WEB_TOUCH_INTERVAL_MS) {
    await SessionModel.updateOne(
      { _id: session._id, revokedAt: null },
      { lastUsedAt: new Date(now), expiresAt: new Date(Math.min(now + WEB_SESSION_IDLE_MS, session.absoluteExpiresAt.getTime())) },
    );
  }
  return true;
}

/** Ends the session an access token belongs to (the web signing out). An invalid or expired token is ignored. */
export async function revokeByAccessToken(accessToken: string) {
  const { userId, sessionId } = await verifyAccessToken(accessToken).catch(() => ({ userId: null, sessionId: null }));
  if (!sessionId) return;
  await SessionModel.updateOne({ _id: sessionId, user: userId, revokedAt: null }, { revokedAt: new Date(), revokedReason: "signed_out" });
}

/**
 * The phone signing itself out. Its biometric sign-in key survives (signing back in with Face ID is the
 * point of it) unless `forgetDevice` is set, as after too many wrong passcodes.
 */
export async function revokeByRefreshToken(refreshToken: string, { forgetDevice = false } = {}) {
  const session = await SessionModel.findOneAndUpdate(
    { refreshTokenHash: hash(refreshToken), revokedAt: null },
    { revokedAt: new Date(), revokedReason: "signed_out" },
  );
  if (session && forgetDevice) {
    await revokeBiometricKeys(session.user, { installationId: session.installationId ?? undefined }, "forgotten");
  }
}

/** Signing a device out from another one also ends its biometric sign-in, so a lost phone stays out. */
export async function revokeSession(userId: string, sessionId: string, reason: "signed_out" | "revoked" = "revoked") {
  const session = await SessionModel.findOneAndUpdate(
    { _id: sessionId, user: userId, revokedAt: null },
    { revokedAt: new Date(), revokedReason: reason },
  );
  if (!session) return false;
  await revokeBiometricKeys(userId, { installationId: session.installationId ?? undefined }, "device_signed_out");
  return true;
}

/**
 * Ends every session of the user except `keepSessionId`, and every biometric sign-in key except this
 * phone's (including phones already signed out that could still sign back in). Returns how many sessions were ended.
 */
export async function revokeOtherSessions(userId: string, keepSessionId?: string) {
  const result = await SessionModel.updateMany(
    { user: userId, revokedAt: null, ...(keepSessionId && { _id: { $ne: keepSessionId } }) },
    { revokedAt: new Date(), revokedReason: "signed_out_everywhere" },
  );
  const current = keepSessionId ? await SessionModel.findById(keepSessionId).select("installationId").lean() : null;
  await BiometricKeyModel.updateMany(
    { user: userId, revokedAt: null, ...(current?.installationId && { installationId: { $ne: current.installationId } }) },
    { revokedAt: new Date(), revokedReason: "signed_out_everywhere" },
  );
  return result.modifiedCount;
}

/**
 * Ends every session of the user and every biometric sign-in key, as after a password reset or deleting
 * the account. Covers any sign-in kept as a Session document. Returns how many sessions were ended.
 */
export function revokeAllSessions(userId: Types.ObjectId | string) {
  return revokeOtherSessions(userId.toString());
}

export async function listSessions(userId: string, currentSessionId?: string) {
  const now = new Date();
  const [sessions, keys] = await Promise.all([
    SessionModel.find({ user: userId, revokedAt: null, expiresAt: { $gt: now } }).sort({ lastUsedAt: -1 }),
    BiometricKeyModel.find({ user: userId, revokedAt: null, expiresAt: { $gt: now } }).select("installationId").lean(),
  ]);
  const withBiometrics = new Set(keys.map((k) => k.installationId));
  return sessions.map((s) => ({
    _id: s.id,
    device: s.device,
    createdAt: (s as unknown as { createdAt: Date }).createdAt,
    lastUsedAt: s.lastUsedAt,
    current: s.id === currentSessionId,
    biometricSignIn: !!s.installationId && withBiometrics.has(s.installationId),
  }));
}
